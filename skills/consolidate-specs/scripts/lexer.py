def directive_matcher(extra=()):
    """Return a function classifying a comment's inner text as "license", "tool" or None.
    Docblock bodies are matched per line, so a directive on the third ` * ` line is seen."""
    tool = [re.compile(p, re.M) for p in (*TOOL_DIRECTIVES, *extra)]
    lic = [re.compile(p, re.M) for p in LICENSE_MARKERS]

    def match(inner):
        body = inner.strip()
        body = re.sub(r"(?m)^[ \t]*\*+[ \t]?", "", body)   # docblock prefixes, per line
        body = body.lstrip("*!/ ").strip()                  # leftover marker halves
        flat = re.sub(r"\s+", " ", body)                    # licence text may wrap mid-phrase
        if any(p.search(flat) for p in lic):
            return "license"
        if any(p.search(body) for p in tool):
            return "tool"
        return None
    return match


