"""String-aware comment lexer for the consolidation runner.

One scan of a source file gives two products:

* comments, each with its exact character span, so a unit is never invented
  inside a string literal, a regex literal or a heredoc;
* code tokens: the file with every comment removed, normalized, so that two
  revisions can be compared token for token (`code-invariance-check`).

Python is lexed by the stdlib `tokenize`; every other language by a small state
machine. A lexer in CERTAIN handles every literal form that can hide a comment
marker; for any other lexer the invariance check reports "cannot prove" and the
test suite decides.

Directives (comments a tool reads, such as `eslint-disable` or `# noqa`) and
license headers are never units: deleting one changes a build, a lint or a legal
notice without changing one code token, so no token comparison can see the loss.
"""
