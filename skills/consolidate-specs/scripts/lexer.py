def language_for(path):
    p = PurePosixPath(str(path).replace("\\", "/"))
    name = p.name.lower()
    if name in _NAMES:
        return _NAMES[name]
    if name.startswith(("dockerfile", "containerfile")):
        return "hashline"
    return _EXT.get(p.suffix.lower())


